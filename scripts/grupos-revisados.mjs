// Grupos musculares revisados de la biblioteca FBE (v0.36) para el recuento de series por músculo.
// La app cuenta cada serie entera en el músculo principal (el primero) y media en cada secundario: es el «recuento
// fraccional» de series, el que mejor predice el crecimiento muscular (Pelland y cols., 2024, metarregresión de
// volumen e hipertrofia). Por eso un secundario solo se apunta si el músculo mueve una articulación a lo largo del
// recorrido y con carga suficiente; los que solo estabilizan o trabajan en isométrico no cuentan. Criterio:
//   · Empujes de pecho (presses, fondos): tríceps y deltoides (anterior). Aperturas, cruces, pec-deck: deltoides.
//   · Tracciones verticales (dominadas, jalones): bíceps. Remos: bíceps y deltoides (posterior). Fuera glúteo e
//     isquios de los remos inclinados (sujetan el tronco en isométrico).
//   · Press militar: tríceps. Elevaciones laterales y frontales, curls, extensiones de tríceps, abdominales y leg
//     curl: solo su músculo (el deltoides de un curl, la espalda de una elevación lateral o el cuádriceps de un crunch
//     no crecen con ese ejercicio).
//   · Sentadillas, prensas, búlgaras, zancadas y step-up: cuádriceps y glúteo; los isquios apenas se alargan con la
//     rodilla flexionada y no crecen con la sentadilla (Kubo y cols., 2019). Fuera el gemelo.
//   · Bisagras (pesos muertos, buenos días): isquios y glúteo; la espalda trabaja en isométrico.
// El principal de cada ejercicio no cambia: es el de Notion. Solo cambian los secundarios.
